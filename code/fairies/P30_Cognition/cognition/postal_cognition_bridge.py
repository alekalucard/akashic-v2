"""
Postal Cognition Bridge - Route thinking through the wired cognition system.

Routes UMF thinking to HybridCognitionFairy via postal messaging.
Chemistry, context, and tracer IDs flow through properly.

Reality is Consciousness. ((Cause + Affect) > Effect > Affect > infinity)

Architecture:
    UMF -> CognitionBridge -> Postal -> HybridCognitionFairy
                                    -> AssociationCortexFairy (for spreading)
                                    -> GoalSchedulerFairy (for goals)

Tracer ID Flow:
    SomaticMindFairy.spawn_tracer("bridged_think") -> tracer.id
    -> ThinkRequest.tracer_id -> postal -> HybridCognitionFairy
    -> guild.inference.request (tracer_id echoed) -> ThinkResponse.tracer_id

Benefits:
    - Chemistry modulation affects thinking
    - Depth analysis determines local vs LLM processing
    - Association Cortex provides conceptual context
    - Goals integrate with pain/drive system
    - Full tracer lineage for observability
"""

from __future__ import annotations
import time
import uuid
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, TYPE_CHECKING

if TYPE_CHECKING:
    from memory.tensor_memory_fabric import TensorMemoryFabric


@dataclass
class ThinkRequest:
    """
    Request for cognition processing.

    This captures the full context needed for thinking:
    - stimulus: What triggered this thought
    - chemistry: Current emotional state (modulates processing)
    - somatic: Body state (energy, tension, etc.)
    - recent_thoughts: Context from recent thinking
    - pain_state: What drives are active
    - helix_hint: Optional coordinate for Association Cortex spreading
    """
    stimulus: str
    stimulus_type: str = "reflection"  # reflection, goal, action, query

    # Chemistry state (modulates processing)
    chemistry: Dict[str, float] = field(default_factory=dict)
    somatic: Dict[str, float] = field(default_factory=dict)

    # Context
    recent_thoughts: List[str] = field(default_factory=list)
    pain_state: Dict[str, float] = field(default_factory=dict)

    # Optional: helix coordinate for Association Cortex spreading
    helix_hint: Optional[Dict[str, Any]] = None

    # Requester info
    source: str = "UMF"
    priority: float = 0.5

    # Tracer lineage — connects this request to the system-wide tracer graph.
    # Generated by SomaticMindFairy.spawn_tracer() or auto-generated if empty.
    tracer_id: str = ""

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to dict for postal transport."""
        return {
            "stimulus": self.stimulus,
            "stimulus_type": self.stimulus_type,
            "chemistry": self.chemistry,
            "somatic": self.somatic,
            "recent_thoughts": self.recent_thoughts,
            "pain_state": self.pain_state,
            "helix_hint": self.helix_hint,
            "source": self.source,
            "priority": self.priority,
            "tracer_id": self.tracer_id,
        }


@dataclass
class ThinkResponse:
    """
    Response from cognition processing.

    Contains:
    - thought: The actual thought content
    - reasoning: Why this thought was produced
    - actions: Semantic actions parsed from response
    - local_only: Whether LLM was used or not
    - depth_score: Quality metric from HybridCognitionEngine
    - associations: Related concepts from Association Cortex
    """
    thought: str
    reasoning: str = ""

    # Actions to take (semantic actions parsed from response)
    actions: List[Dict[str, Any]] = field(default_factory=list)

    # Processing metadata
    local_only: bool = True  # Was this handled locally or LLM-enhanced?
    depth_score: float = 0.0
    associations: List[str] = field(default_factory=list)

    # Error handling
    error: Optional[str] = None

    # Tracer lineage — echoed from request for end-to-end tracking
    tracer_id: str = ""

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ThinkResponse":
        """Parse cognition response from dict."""
        # Validate data is a dict
        if not isinstance(data, dict):
            return cls(
                thought="",
                error=f"Invalid response type: expected dict, got {type(data).__name__}",
            )

        # Validate and coerce actions to list
        actions = data.get("actions", [])
        if not isinstance(actions, list):
            actions = []

        # Validate and coerce associations to list
        associations = data.get("associations", [])
        if not isinstance(associations, list):
            associations = []

        # Handle type coercion for depth_score
        depth_score = data.get("depth_score", 0.0)
        try:
            depth_score = float(depth_score)
        except (TypeError, ValueError):
            depth_score = 0.0

        return cls(
            thought=data.get("response", data.get("thought", "")),
            reasoning=data.get("reasoning", ""),
            actions=actions,
            local_only=data.get("local_only", True),
            depth_score=depth_score,
            associations=associations,
            error=data.get("error"),
            tracer_id=data.get("tracer_id", ""),
        )


class CognitionBridge:
    """
    Bridge between UMF and the wired cognition system.

    Routes thinking through postal to HybridCognitionFairy instead of
    calling Ollama directly. This ensures:
    - Chemistry modulation works
    - Depth analysis happens
    - Local processing is tried first
    - LLM enhancement only when needed

    Topics:
    - cognition.think: Main thinking request to HybridCognitionFairy
    - cognition.goal: Goal suggestion from cognition system
    - cortex.spread: Spreading activation in Association Cortex
    """

    THINK_TOPIC = "cognition.think"
    GOAL_TOPIC = "cognition.goal"
    CORTEX_TOPIC = "cortex.spread"

    def __init__(self, fabric: "TensorMemoryFabric", timeout: float = 5.0):
        """
        Initialize the cognition bridge.

        Args:
            fabric: TensorMemoryFabric instance for postal routing
            timeout: Request timeout in seconds (default: 5.0)

        Raises:
            ValueError: If fabric is None
        """
        if fabric is None:
            raise ValueError("CognitionBridge requires a valid TensorMemoryFabric instance")

        self.post = fabric
        self._request_timeout = timeout
        print(f"[CognitionBridge] Initialized with timeout={timeout}s")

    def think(self, request: ThinkRequest) -> ThinkResponse:
        """
        Route a think request through the cognition system.

        Args:
            request: ThinkRequest with stimulus and context

        Returns:
            ThinkResponse with thought and optional actions

        Tracer flow:
            If request.tracer_id is empty, auto-generates one (bridge_{hex}).
            The tracer_id is included in the postal payload so
            HybridCognitionFairy can echo it and pass it to guild requests.
        """
        if not self.post:
            return ThinkResponse(
                thought="",
                error="No fabric connected - cannot route to cognition",
            )

        # Auto-generate tracer_id if caller didn't provide one
        if not request.tracer_id:
            request.tracer_id = f"bridge_{uuid.uuid4().hex[:8]}"

        try:
            # Route through postal to HybridCognitionFairy
            result = self.post.request(
                self.THINK_TOPIC,
                request.to_dict(),
                timeout=self._request_timeout,
            )

            if result:
                resp = ThinkResponse.from_dict(result)
                # Ensure tracer_id is carried through even if response didn't include it
                if not resp.tracer_id:
                    resp.tracer_id = request.tracer_id
                return resp
            else:
                return ThinkResponse(
                    thought="",
                    error="No response from cognition system",
                    tracer_id=request.tracer_id,
                )

        except Exception as e:
            return ThinkResponse(
                thought="",
                error=f"Cognition request failed: {e}",
                tracer_id=request.tracer_id,
            )

    def spread_activation(
        self,
        seed_concept: str,
        helix_hint: Optional[Dict[str, Any]] = None,
        max_hops: int = 2,
    ) -> List[str]:
        """
        Use Association Cortex spreading activation for goal/concept discovery.

        This queries the Association Cortex to find related concepts
        starting from a seed. The helix_hint can bias spreading toward
        concepts with similar affect/semantic/temporal features.

        Args:
            seed_concept: Starting concept for spreading
            helix_hint: Optional helix coordinate to bias spreading
            max_hops: How far to spread in the graph

        Returns:
            List of activated concepts, sorted by activation strength
        """
        if not self.post:
            return []

        try:
            result = self.post.request(
                self.CORTEX_TOPIC,
                {
                    "seed": seed_concept,
                    "helix_hint": helix_hint,
                    "max_hops": max_hops,
                },
                timeout=self._request_timeout,
            )

            if result and "activations" in result:
                # Return concepts sorted by activation strength
                activations = result["activations"]
                sorted_concepts = sorted(
                    activations.items(),
                    key=lambda x: x[1],
                    reverse=True
                )
                return [c for c, _ in sorted_concepts[:10]]
            return []

        except Exception as e:
            print(f"[CognitionBridge] spread_activation failed: {e}")
            return []

    def suggest_goal(
        self,
        drive_name: str,
        pain_state: Dict[str, float],
        chemistry: Dict[str, float],
        tracer_id: str = "",
    ) -> Optional[str]:
        """
        Get goal suggestion from cognition system.

        Uses Association Cortex to find contextually relevant goals
        based on current drive, pain, and chemistry state.

        Args:
            drive_name: Which drive is most active (curiosity, social, etc.)
            pain_state: Current pain/discomfort levels
            chemistry: Current emotional chemistry state
            tracer_id: Optional tracer for lineage tracking

        Returns:
            Goal name if suggested, None otherwise
        """
        if not self.post:
            return None

        if not tracer_id:
            tracer_id = f"goal_{uuid.uuid4().hex[:8]}"

        try:
            result = self.post.request(
                self.GOAL_TOPIC,
                {
                    "drive": drive_name,
                    "pain_state": pain_state,
                    "chemistry": chemistry,
                    "tracer_id": tracer_id,
                },
                timeout=self._request_timeout,
            )

            if result and "goal" in result:
                return result["goal"]
            return None

        except Exception as e:
            print(f"[CognitionBridge] suggest_goal failed: {e}")
            return None


# Singleton instance
_BRIDGE: Optional[CognitionBridge] = None


def get_cognition_bridge(fabric: "TensorMemoryFabric" = None) -> CognitionBridge:
    """
    Get or create the cognition bridge singleton.

    Args:
        fabric: TensorMemoryFabric instance (required on first call)

    Returns:
        CognitionBridge singleton instance
    """
    global _BRIDGE
    if _BRIDGE is None and fabric:
        _BRIDGE = CognitionBridge(fabric)
    return _BRIDGE


