# ── Reflection infrastructure (stub if not available) ─────────────────────────
@dataclass
class Reflection:
    """A reflection that can be pondered and crystallized."""
    id: str = field(default_factory=lambda: uuid.uuid4().hex[:12])
    observation: str = ""
    source_fairy: str = ""
    pondered_count: int = 0
    crystallized: bool = False


class ReflectionPool:
    """Pool for managing reflections (stub implementation)."""
    def __init__(self):
        self._reflections: List[Reflection] = []

    def reflect(self, **kwargs) -> Reflection:
        r = Reflection(
            observation=kwargs.get("observation", ""),
            source_fairy=kwargs.get("source_fairy", ""),
        )
        self._reflections.append(r)
        return r

    def ponder_cycle(self, n: int = 5) -> List[Reflection]:
        """Age reflections by incrementing pondered_count."""
        pondered = []
        for r in self._reflections[-n:]:
            r.pondered_count += 1
            if r.pondered_count >= 3:
                r.crystallized = True
            pondered.append(r)
        return pondered

    def pop_crystallized(self) -> Optional[Reflection]:
        """Pop a crystallized reflection if any."""
        for i, r in enumerate(self._reflections):
            if r.crystallized:
                return self._reflections.pop(i)
        return None


_REFLECTION_POOL: Optional[ReflectionPool] = None


def get_reflection_pool() -> ReflectionPool:
    """Get the singleton reflection pool."""
    global _REFLECTION_POOL
    if _REFLECTION_POOL is None:
        _REFLECTION_POOL = ReflectionPool()
    return _REFLECTION_POOL


