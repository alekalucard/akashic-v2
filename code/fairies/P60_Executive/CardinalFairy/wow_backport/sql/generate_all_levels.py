#!/usr/bin/env python3
"""
Generate complete level stats SQL for Fairy class (ID 12)
Run this to create full 1-80 stats for all races.
"""

# Fairy races and their base stats at level 1
# Format: (str, agi, sta, int, spi)
FAIRY_RACES = {
    1: ("Human", (18, 18, 19, 22, 24)),
    4: ("Night Elf", (15, 22, 18, 22, 24)),
    5: ("Forsaken", (16, 16, 20, 20, 28)),
    7: ("Gnome", (13, 20, 18, 27, 22)),
    10: ("Blood Elf", (15, 20, 17, 26, 22)),
    11: ("Draenei", (19, 15, 18, 23, 25)),
}

# Stat growth per level (based on Priest growth curves, Fairy-adjusted)
# Fairies grow faster in Spirit and Intellect
STAT_GROWTH = {
    "str": 0.75,   # Slow strength growth
    "agi": 0.75,   # Slow agility growth
    "sta": 1.3,    # Moderate stamina growth
    "inte": 1.8,   # High intellect growth
    "spi": 2.0,    # Very high spirit growth
}

def calculate_stat(base: int, level: int, growth: float) -> int:
    """Calculate stat at given level using growth curve."""
    # Growth formula: base + (level-1) * growth + (level-1)^1.5 * growth * 0.1
    return int(base + (level - 1) * growth + ((level - 1) ** 1.5) * growth * 0.1)

def generate_levelstats_sql():
    """Generate INSERT statements for player_levelstats."""
    lines = [
        "-- ============================================================================",
        "-- PLAYER_LEVELSTATS - Full 1-80 for all Fairy races",
        "-- Generated by generate_all_levels.py",
        "-- ============================================================================",
        "",
        "DELETE FROM `player_levelstats` WHERE `class` = 12;",
        "",
    ]

    for race_id, (race_name, base_stats) in FAIRY_RACES.items():
        lines.append(f"-- {race_name} Fairy (Race {race_id})")

        for level in range(1, 81):
            str_val = calculate_stat(base_stats[0], level, STAT_GROWTH["str"])
            agi_val = calculate_stat(base_stats[1], level, STAT_GROWTH["agi"])
            sta_val = calculate_stat(base_stats[2], level, STAT_GROWTH["sta"])
            int_val = calculate_stat(base_stats[3], level, STAT_GROWTH["inte"])
            spi_val = calculate_stat(base_stats[4], level, STAT_GROWTH["spi"])

            lines.append(
                f"INSERT INTO `player_levelstats` (`race`, `class`, `level`, `str`, `agi`, `sta`, `inte`, `spi`) "
                f"VALUES ({race_id}, 12, {level}, {str_val}, {agi_val}, {sta_val}, {int_val}, {spi_val});"
            )

        lines.append("")

    return "\n".join(lines)

def main():
    sql = generate_levelstats_sql()
    output_path = "fairy_class_levelstats_full.sql"

    with open(output_path, "w") as f:
        f.write(sql)

    print(f"Generated {output_path}")
    print(f"Total INSERT statements: {6 * 80}")  # 6 races x 80 levels

if __name__ == "__main__":
    main()
