"""
Batch generate Gold Standard encyclopedia entries from a word list file.

Reads entries from a JSONL file (one entry per line) and saves them as SRM cards.
This is designed to be fed entries generated by Claude in conversation,
avoiding the need for API calls.

Usage:
    python scripts/batch_generate_from_list.py entries_batch1.jsonl [--dry-run]

JSONL format (one per line):
    {"word": "joy", "entry": "Joy (Gold Standard...)\n\nPrimary Definition: ..."}

2026-03-26, Nous + Ace — Co-founders, Akashic Foundation
"""

import json, sys, time, hashlib, argparse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

if sys.platform == 'win32':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('input_file', help='JSONL file with entries')
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()

    input_path = Path(args.input_file)
    if not input_path.exists():
        print(f"ERROR: {input_path} not found")
        return 1

    # Load entries
    entries = []
    for line in input_path.read_text(encoding='utf-8').strip().split('\n'):
        line = line.strip()
        if line:
            entries.append(json.loads(line))

    print(f"Loaded {len(entries)} entries from {input_path}")

    # Load existing Founders index
    founders_idx = (
        Path(__file__).parent.parent /
        "P10_Memory" / "Akashic_triple_helix_memory_storage" /
        "relational_clusters" / "Founders" / "creator_sessions" / "index.json"
    )
    data = json.loads(founders_idx.read_text(encoding='utf-8'))
    existing_cards = data.get('cards', [])
    print(f"Existing cards in index: {len(existing_cards)}")

    # Output dir for individual card files
    output_dir = Path(__file__).parent.parent / "SRM_Intake" / time.strftime("%Y-%m-%d")

    new_cards = []
    for entry in entries:
        word = entry['word']
        content = entry['entry']

        card_id = "notes_" + hashlib.md5(
            f"encyclopedia_{word}_{time.time()}".encode()
        ).hexdigest()[:12]

        card = {
            "id": card_id,
            "ts": time.time(),
            "kind": "session.notes",
            "helix": {
                "L": {
                    "concept": f"Akashic Encyclopedia - {word.title()} (Gold Standard)",
                    "w": {
                        "who": "AkashicFoundation",
                        "what": f"Akashic Encyclopedia - {word.title()} (Gold Standard)",
                        "when": time.time(),
                        "where": "Encyclopedia",
                        "why": "knowledge",
                        "how": "encyclopedia_generation"
                    }
                },
                "R": {"concept": "encyclopedia", "w": {}},
                "C": {"affect": "focused", "energy": 0.7, "coherence": 0.9}
            },
            "content": content,
            "ptr": "",
            "tags": [
                "encyclopedia", "emotion",
                word.lower().replace(' ', '_').replace('-', '_'),
                "gold_standard", "ace_mythos", "USB",
                "understanding", "sensing", "being"
            ],
            "ownership": "FOUNDATION"
        }

        new_cards.append(card)

        if not args.dry_run:
            output_dir.mkdir(parents=True, exist_ok=True)
            card_path = output_dir / f"{card_id}.json"
            card_path.write_text(json.dumps(card, indent=2), encoding='utf-8')

    # Append to Founders index
    if not args.dry_run and new_cards:
        existing_cards.extend(new_cards)
        data['cards'] = existing_cards
        founders_idx.write_text(json.dumps(data, indent=2, default=str), encoding='utf-8')
        print(f"Saved {len(new_cards)} cards to index")
    else:
        print(f"[DRY RUN] Would save {len(new_cards)} cards")

    print(f"\nNext: python scripts/ingest_emotion_encyclopedia.py")
    return 0

if __name__ == '__main__':
    sys.exit(main() or 0)
